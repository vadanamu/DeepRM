#ifndef DEEPRM_PILEUP_LOGIT_EXCEPTIONS_H_
#define DEEPRM_PILEUP_LOGIT_EXCEPTIONS_H_

#include <array>
#include <cstdint>

namespace deeprm {

// A probability (float32 bits) whose calibration logit differs between the
// C library and NumPy, and NumPy's logit (float32 bits).
struct LogitException {
  std::uint32_t pred_bits;
  std::uint32_t logit_bits;
};

// Generated by tests/make_logit_exceptions.py from every float32 in [0, 1],
// sorted by pred_bits.
inline constexpr std::array<LogitException, 0> kLogitExceptions = {};

}  // namespace deeprm

#endif  // DEEPRM_PILEUP_LOGIT_EXCEPTIONS_H_
