"""make_logit_exceptions.py BINARY [JOBS]: prints pileup/logit_exceptions.h.

Compares, for every float32 probability, the calibration logit the C library gives (deeprm_pileup logit-range) with
the one NumPy gives, and lists the inputs where they differ with NumPy's value. Run it with the NumPy the Python
pileup uses (2.4.6, AVX512)."""
import multiprocessing as mp
import sys

import numpy as np

from float_ranges import probability_ranges, run_tool

BINARY = sys.argv[1]

